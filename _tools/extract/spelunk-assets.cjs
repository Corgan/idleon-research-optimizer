const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const mbs = require('./mbs.cjs');

async function main() {
  const root = path.resolve(__dirname, '..', '..');
  const { SpelunkRocks } = await import(pathToFileURL(path.join(root, 'js', 'stats', 'data', 'game', 'customlists.js')));
  const letters = '_abcdefghijklmnopqrstuvwxyz';
  const pak = mbs.openGamePak();
  const out = path.join(root, 'assets', 'spelunking');
  fs.mkdirSync(out, { recursive: true });
  const names = new Set();
  for (let cave = 0; cave < SpelunkRocks.length; cave++) {
    for (let type = 0; type < SpelunkRocks[cave].length - 1; type++) names.add(`CaveRock${letters[cave]}${type}`);
    names.add(`CaveBoss${cave}`);
    names.add(`CaveRockExit${cave}`);
    names.add(`CaveTile${cave}`);
    names.add(`CaveDoor${cave}`);
  }
  for (let i = 0; i < 12; i++) names.add(`CaveElix${i}`);
  names.add('CaveRope');
  for (let i = 0; i < 5; i++) names.add(`CaveTool${i}`);
  for (let i = 0; i < 5; i++) names.add(`CaveAmber${i}`);
  for (const name of ['CaveElixSq', 'CaveSelectPlayer', 'CaveStamC', 'Blingbag', 'Quest99_x1',
    'ExaltFrag', 'SnailMail', 'Quest90_x1', 'SigilSyrup', 'Quest102_x1', 'CaveGoldPiece_x1',
    'W7item0_x1', 'W7item1_x1', 'W7item2_x1', 'W7item3_x1']) names.add(name);
  for (const key of pak.manifest.keys()) {
    const match = /^assets\/data\/(ClassIcons\d+)\.png$/.exec(key);
    if (match) names.add(match[1]);
  }
  const files = {};
  for (const name of names) {
    const source = `assets/data/${name}.png`;
    if (!pak.manifest.has(source)) {
      throw new Error(`Missing native art: ${source}`);
    }
    const buf = pak.get(source);
    files[name] = { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20), sha256: mbs.sha256(buf), source };
    fs.writeFileSync(path.join(out, `${name}.png`), buf);
  }
  const sourceHash = mbs.sha256(fs.readFileSync(path.join(root, 'src', 'N.new.formatted.js')));
  fs.writeFileSync(path.join(root, 'js', 'stats', 'data', 'game', 'spelunk-sprites.js'),
    `// Generated by _tools/extract/spelunk-assets.cjs. Native 1x dimensions.\nexport const SPELUNK_SPRITES = ${JSON.stringify(files, null, 2)};\nexport const SPELUNK_SOURCE_HASH = '${sourceHash}';\n`);
  console.log(`Extracted ${Object.keys(files).length} Spelunking images.`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
